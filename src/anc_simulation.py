"""FxNLMS-style ANC simulation driven by an actual recorded audio segment.

Important: MIMII has no measured reference/error microphone pair or measured
secondary path. This module therefore uses real audio as the excitation signal
but applies explicitly assumed FIR paths. Every output is a numerical ANC
simulation result, not a physical noise-reduction measurement.
"""
from __future__ import annotations

import numpy as np
from scipy.signal import lfilter

from config import (
    ANC_SAMPLE_RATE,
    PRIMARY_PATH,
    SECONDARY_PATH,
    SECONDARY_PATH_ESTIMATE,
)
from src.audio_io import resample_audio


def rms(values: np.ndarray) -> float:
    x = np.asarray(values, dtype=np.float64)
    return float(np.sqrt(np.mean(x * x) + 1e-15))


def noise_reduction_db(primary: np.ndarray, residual: np.ndarray) -> float:
    """Signal-level RMS ratio in dB; not calibrated SPL attenuation."""
    return float(20.0 * np.log10((rms(primary) + 1e-15) / (rms(residual) + 1e-15)))


def run_fxnlms_on_recording(
    audio: np.ndarray,
    source_sample_rate: int,
    mu: float,
    filter_len: int,
    *,
    sample_rate: int = ANC_SAMPLE_RATE,
    primary_path: tuple[float, ...] = PRIMARY_PATH,
    secondary_path: tuple[float, ...] = SECONDARY_PATH,
    secondary_path_estimate: tuple[float, ...] = SECONDARY_PATH_ESTIMATE,
    max_weight_norm: float = 100.0,
) -> dict:
    """Run a baseline FxNLMS-style algorithm using a real recording as excitation.

    The real recording is resampled and normalized to unit RMS for fair settings
    comparison. The disturbance is generated by filtering that recording through
    an assumed primary FIR path; the control output passes through an assumed
    secondary FIR path. Therefore the controller is tested against modelled
    paths, not measured acoustic hardware.
    """
    if not 0.0 <= float(mu) <= 1.0:
        raise ValueError("mu must be between 0 and 1")
    if int(filter_len) < 2:
        raise ValueError("filter_len must be at least 2")

    x = resample_audio(np.asarray(audio, dtype=np.float32).reshape(-1), source_sample_rate, sample_rate).astype(np.float64)
    if x.size < max(1024, filter_len * 8):
        raise ValueError("Recording segment is too short for ANC simulation")
    x -= np.mean(x)
    input_rms = rms(x)
    if input_rms < 1e-10:
        raise ValueError("Recording has near-zero audio energy")
    x /= input_rms

    p = np.asarray(primary_path, dtype=np.float64)
    s = np.asarray(secondary_path, dtype=np.float64)
    shat = np.asarray(secondary_path_estimate, dtype=np.float64)
    if p.size == 0 or s.size == 0 or shat.size == 0:
        raise ValueError("FIR paths cannot be empty")

    # The modelled disturbance is driven by the real recording; no random or
    # synthetic excitation signal is generated here.
    desired = lfilter(p, [1.0], x)
    filtered_reference = lfilter(shat, [1.0], x)

    weights = np.zeros(int(filter_len), dtype=np.float64)
    reference_buffer = np.zeros(int(filter_len), dtype=np.float64)
    filtered_buffer = np.zeros(int(filter_len), dtype=np.float64)
    secondary_history = np.zeros(s.size, dtype=np.float64)

    control = np.zeros(x.size, dtype=np.float64)
    secondary_output = np.zeros(x.size, dtype=np.float64)
    residual = np.zeros(x.size, dtype=np.float64)
    weight_norm = np.zeros(x.size, dtype=np.float64)
    stable = True
    completed_samples = x.size

    for index in range(x.size):
        reference_buffer[1:] = reference_buffer[:-1]
        reference_buffer[0] = x[index]
        filtered_buffer[1:] = filtered_buffer[:-1]
        filtered_buffer[0] = filtered_reference[index]

        control[index] = np.dot(weights, reference_buffer)
        secondary_history[1:] = secondary_history[:-1]
        secondary_history[0] = control[index]
        secondary_output[index] = np.dot(s, secondary_history)
        residual[index] = desired[index] + secondary_output[index]

        denominator = 1e-8 + float(np.dot(filtered_buffer, filtered_buffer))
        weights -= (float(mu) * residual[index] / denominator) * filtered_buffer
        weight_norm[index] = float(np.linalg.norm(weights))

        if not np.isfinite(weight_norm[index]) or weight_norm[index] > max_weight_norm:
            stable = False
            completed_samples = index + 1
            # Mark the configuration unstable; do not continue with divergent values.
            residual[index:] = np.nan
            control[index:] = np.nan
            secondary_output[index:] = np.nan
            weight_norm[index:] = np.nan
            break

    valid_residual = residual[np.isfinite(residual)]
    valid_primary = desired[:valid_residual.size]
    valid_control = control[np.isfinite(control)]
    if valid_residual.size == 0:
        full_nr = steady_nr = control_ratio_db = float("nan")
    else:
        full_nr = noise_reduction_db(valid_primary, valid_residual)
        start = int(valid_residual.size * 0.75)
        steady_nr = noise_reduction_db(valid_primary[start:], valid_residual[start:])
        control_ratio_db = float(20 * np.log10((rms(valid_control) + 1e-15) / (rms(valid_primary) + 1e-15)))

    return {
        "reference": x,
        "primary": desired,
        "control": control,
        "secondary_output": secondary_output,
        "residual": residual,
        "filter_norm": weight_norm,
        "sample_rate": int(sample_rate),
        "mu": float(mu),
        "filter_len": int(filter_len),
        "stable": bool(stable),
        "completed_samples": int(completed_samples),
        "input_rms": rms(desired),
        "residual_rms": rms(valid_residual) if valid_residual.size else float("nan"),
        "noise_reduction_db": full_nr,
        "steady_state_noise_reduction_db": steady_nr,
        "control_to_primary_rms_db": control_ratio_db,
        "evidence_type": "simulation using real recorded audio and assumed FIR acoustic paths",
    }


def configuration_utility(metrics: dict) -> float:
    """Scalar selection target: favour reduction but discourage excessive control.

    A config is marked infeasible if it diverges or its control RMS exceeds the
    modelled primary disturbance RMS by more than 6 dB. Among feasible settings,
    select high steady-state signal-level reduction with a small penalty when
    control RMS exceeds primary RMS. These are explicit simulation-design
    constraints and must be sensitivity-tested, not treated as universal physics.
    """
    if not metrics.get("stable", False):
        return -100.0
    nr = float(metrics.get("steady_state_noise_reduction_db", float("nan")))
    ctrl_db = float(metrics.get("control_to_primary_rms_db", float("nan")))
    if not np.isfinite(nr) or not np.isfinite(ctrl_db):
        return -100.0
    if ctrl_db > 6.0:
        return -100.0
    penalty = 0.05 * max(0.0, ctrl_db)
    return float(nr - penalty)
